def _clock():
    return datetime.now(timezone.utc)


def _safe_cell(value):
    if isinstance(value, (dict, list, tuple)):
        value = canonical_json(value)
    elif value is None:
        return ""
    elif isinstance(value, bool):
        return "true" if value else "false"
    else:
        value = str(value)
    # Prevent spreadsheet formula execution without silently dropping source text.
    return "'" + value if value.startswith(("=", "+", "-", "@")) else value


class ExportService:
    def __init__(self, dsn, *, registry, projection, clock=None):
        self.dsn, self.registry, self.projection = dsn, registry, projection
        self.clock = clock or _clock

    def initialize(self):
        with self.registry.connect() as db:
            db.execute("SELECT pg_advisory_xact_lock(20261104,6)")
            db.execute(SCHEMA)
            db.execute(MIGRATIONS)

    @staticmethod
    def route(path):
        if path == "/exports":
            return "list", None
        match = re.fullmatch(r"/exports/([^/]+)(/content|/cancel)?", path)
        if match:
            return ({"/content": "content", "/cancel": "cancel"}.get(match[2], "detail"), match[1])
        raise DomainError("not_found", "No export route matches", 404)

    def _subject(self, principal):
        return identity("export-subject", {
            "subject": principal.subject_ref, "grants": sorted(principal.grant_ids)})

    @staticmethod
    def _read_route(source_path, filters):
        if source_path == "/observations/{id}/items":
            run_id = filters.get("id")
            if not run_id:
                raise DomainError("invalid_argument", "Observation item export requires filters.id")
            clean = {k: v for k, v in filters.items() if k != "id"}
            return "/observations/" + quote(run_id, safe="") + "/items", clean, "items"
        return source_path, dict(filters), {
            "/keywords": "keywords", "/query-variants": "query_variants",
            "/observations": "observations", "/serp-features": "features"}[source_path]

    def create(self, principal, body, *, idempotency_key, now):
        text(idempotency_key, "Idempotency-Key", maximum=120)
        if (not isinstance(body, dict)
                or set(body) - {"source_path", "filters", "fields", "format", "async"}):
            raise DomainError("invalid_argument", "Export body has unknown or missing fields")
        source_path = body.get("source_path")
        if source_path not in EXPORTABLE:
            raise DomainError("not_covered", "This source path is not exportable", 501)
        filters = body.get("filters") or {}
        if not isinstance(filters, dict) or "cursor" in filters or "limit" in filters:
            raise DomainError("invalid_argument", "Export filters cannot contain cursor/limit")
        fields, fmt = body.get("fields"), body.get("format")
        permitted_fields = ROUTE_FIELDS[source_path]
        if (not isinstance(fields, list) or not fields or len(fields) > len(permitted_fields)
                or any(not isinstance(f, str) or f not in permitted_fields for f in fields)
                or len(set(fields)) != len(fields)):
            raise DomainError("invalid_argument", "Export fields must be a unique explicit allowlist")
        if fmt not in {"jsonl", "csv"}:
            raise DomainError("invalid_argument", "Export format must be jsonl or csv")
        asynchronous = body.get("async", False)
        if type(asynchronous) is not bool:
            raise DomainError("invalid_argument", "Export async must be a boolean")
        request_hash = identity("export-request", dict(
            source_path=source_path, filters=filters, fields=fields, format=fmt,
            asynchronous=asynchronous))
        with self.registry.connect() as db:
            existing = db.execute("""SELECT e.*,
                                     COALESCE(m.subject_scope,e.subject_scope) AS subject_scope
                                     FROM sf_google_exports e
                                     LEFT JOIN sf_google_export_manifests m
                                     ON m.tenant_id=e.tenant_id AND m.manifest_id=e.manifest_id
                                     WHERE e.tenant_id=%s AND e.idempotency_key=%s""",
                                  (principal.tenant_id, idempotency_key)).fetchone()
        if existing:
            if existing["request_hash"] != request_hash:
                raise DomainError("idempotency_conflict", "Idempotency key was used for another export", 409)
            self._readable(principal, existing, now)
            return self._public(existing)

        self.projection._ready(principal, now)
        expanded, read_filters, key = self._read_route(source_path, filters)
        page = self.projection.read(principal, expanded, {**read_filters, "limit": "100"}, now=now)
        rows = page[key]
        if page["next_cursor"] is not None or asynchronous:
            for row in rows:
                evidence = row.get("evidence")
                if not evidence:
                    raise DomainError(
                        "source_error", "Frozen row lacks a licensed evidence reference", 503)
                self.projection._rights(
                    principal, EvidenceReference(**evidence), use="export", now=now)
            if page["evidence_expires_at"] and parse_time(
                    page["evidence_expires_at"]) <= parse_time(now):
                raise DomainError("expired", "Manifest evidence has expired", 410)
            request = {
                "source_path": source_path, "filters": filters,
                "fields": fields, "format": fmt, "async": asynchronous,
            }
            export_id = "export:" + uuid4().hex
            filename = "google-domain-export." + fmt
            content_type = "application/x-ndjson" if fmt == "jsonl" else "text/csv"
            expiry = parse_time(now) + timedelta(hours=24)
            with self.registry.connect() as db:
                db.execute("SELECT pg_advisory_xact_lock(hashtextextended(%s,20261106))",
                           (principal.tenant_id,))
                self.registry.assert_current(principal, now=now, db=db)
                conflict = db.execute("""SELECT e.*,
                                         COALESCE(m.subject_scope,e.subject_scope) AS subject_scope
                                         FROM sf_google_exports e
                                         LEFT JOIN sf_google_export_manifests m
                                         ON m.tenant_id=e.tenant_id AND m.manifest_id=e.manifest_id
                                         WHERE e.tenant_id=%s AND e.idempotency_key=%s""",
                                      (principal.tenant_id, idempotency_key)).fetchone()
                if conflict:
                    if conflict["request_hash"] != request_hash:
                        raise DomainError(
                            "idempotency_conflict",
                            "Idempotency key was used for another export", 409)
                    return self._public(conflict)
                db.execute("""INSERT INTO sf_google_exports
                    (tenant_id,export_id,idempotency_key,request_hash,manifest_id,format,
                     fields,status,filename,row_count,content,content_type,content_sha256,
                     created_at,completed_at,expires_at,reason,subject_scope,subject_ref,request,
                     progress_done,progress_total,worker_ref,lease_token,lease_expires_at,
                     heartbeat_at,attempts,cancel_requested,error_code,error_message)
                    VALUES(%s,%s,%s,%s,NULL,%s,%s,'queued',%s,0,NULL,%s,NULL,
                           %s,NULL,%s,NULL,%s,%s,%s,0,NULL,NULL,NULL,NULL,NULL,0,false,NULL,NULL)""",
                           (principal.tenant_id, export_id, idempotency_key, request_hash,
                            fmt, Jsonb(fields), filename, content_type, parse_time(now), expiry,
                            self._subject(principal), principal.subject_ref, Jsonb(request)))
                row = db.execute("""SELECT * FROM sf_google_exports
                                    WHERE tenant_id=%s AND export_id=%s""",
                                 (principal.tenant_id, export_id)).fetchone()
            return self._public(row)
        if not page["evidence_expires_at"]:
            # Empty all-time exports have no selected Whale version to pin.
            raise DomainError("partial_result", "A frozen export needs at least one pinned evidence version", 409)
        for row in rows:
            evidence = row.get("evidence")
            if not evidence:
                raise DomainError("source_error", "Frozen row lacks a licensed evidence reference", 503)
            self.projection._rights(
                principal, EvidenceReference(**evidence), use="export", now=now)
        expiry = min(parse_time(page["evidence_expires_at"]), parse_time(now) + timedelta(hours=24))
        data = [{field: row.get(field) for field in fields} for row in rows]
        rights_at_query, seen_refs = [], set()
        for row in rows:
            ref = EvidenceReference(**row["evidence"])
            if ref.grant_id in seen_refs:
                continue
            seen_refs.add(ref.grant_id)
            grant = self.registry.grant(principal.tenant_id, ref.grant_id)
            rights_at_query.append({
                "grant_id": grant.grant_id, "grant_version": grant.version,
                "asset_id": grant.asset_id, "source_adapter": grant.source_adapter,
                "source_version": grant.source_version, "allowed_uses": sorted(grant.uses),
                "fields": sorted(ref.fields), "expires_at": utc_text(grant.expires_at),
            })
        method_versions = {"projection": page["projection_version"], "export": "1"}
        manifest = identity("export-manifest", dict(
            tenant_id=principal.tenant_id, subject_scope=self._subject(principal),
            projection_revision=page["projection_revision"], source_path=source_path,
            filters=filters, fields=fields, method_versions=method_versions,
            rights_at_query=rights_at_query, data=data,
            evidence=page["evidence_expires_at"]))
        rendered = self._render(rows, fields, fmt)
        digest = "sha256:" + hashlib.sha256(rendered).hexdigest()
        export_id, filename = "export:" + uuid4().hex, "google-domain-export." + fmt
        with self.registry.connect() as db:
            db.execute("SELECT pg_advisory_xact_lock(hashtextextended(%s,20261106))",
                       (principal.tenant_id,))
            self.registry.assert_current(principal, now=now, db=db)
            conflict = db.execute("""SELECT e.*,
                                     COALESCE(m.subject_scope,e.subject_scope) AS subject_scope
                                     FROM sf_google_exports e
                                     LEFT JOIN sf_google_export_manifests m
                                     ON m.tenant_id=e.tenant_id AND m.manifest_id=e.manifest_id
                                     WHERE e.tenant_id=%s AND e.idempotency_key=%s""",
                                  (principal.tenant_id, idempotency_key)).fetchone()
            if conflict:
                if conflict["request_hash"] != request_hash:
                    raise DomainError("idempotency_conflict", "Idempotency key was used for another export", 409)
                if (parse_time(now) >= conflict["expires_at"]
                        or self._subject(principal) != conflict["subject_scope"]):
                    raise DomainError("expired", "Existing export is expired or no longer in scope", 410)
                return self._public(conflict)
            existing_manifest = db.execute(
                """SELECT expires_at FROM sf_google_export_manifests
                   WHERE tenant_id=%s AND manifest_id=%s""",
                (principal.tenant_id, manifest),
            ).fetchone()
            if existing_manifest:
                # CSV/JSONL and repeated exports may share one frozen snapshot.
                expiry = min(
                    parse_time(now) + timedelta(hours=24),
                    parse_time(existing_manifest["expires_at"]),
                )
            else:
                db.execute("""INSERT INTO sf_google_export_manifests
                              VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)""",
                           (principal.tenant_id, manifest, parse_time(now), expiry,
                            self._subject(principal), page["projection_revision"], source_path,
                            Jsonb(filters), Jsonb(method_versions), Jsonb(rights_at_query), request_hash,
                            Jsonb(data),
                            Jsonb(page)))
            db.execute("""INSERT INTO sf_google_exports
                          (tenant_id,export_id,idempotency_key,request_hash,manifest_id,format,
                           fields,status,filename,row_count,content,content_type,content_sha256,
                           created_at,completed_at,expires_at,reason,subject_scope,subject_ref,request,
                           progress_done,progress_total,worker_ref,lease_token,lease_expires_at,
                           heartbeat_at,attempts,cancel_requested,error_code,error_message)
                          VALUES(%s,%s,%s,%s,%s,%s,%s,'succeeded',%s,%s,NULL,%s,%s,
                                 %s,%s,%s,NULL,%s,%s,NULL,%s,%s,NULL,NULL,NULL,NULL,0,false,NULL,NULL)""",
                       (principal.tenant_id, export_id, idempotency_key, request_hash, manifest,
                        fmt, Jsonb(fields), filename,
                        len(rows), "application/x-ndjson" if fmt == "jsonl" else "text/csv",
                        digest, parse_time(now), parse_time(now), expiry,
                        self._subject(principal), principal.subject_ref, len(rows), len(rows)))
            row = db.execute("SELECT * FROM sf_google_exports WHERE tenant_id=%s AND export_id=%s",
                             (principal.tenant_id, export_id)).fetchone()
        return self._public(row)

    @staticmethod
    def _render(rows, fields, fmt, *, header=True):
        if fmt == "jsonl":
            return "".join(canonical_json({f: row.get(f) for f in fields}) + "\n"
                           for row in rows).encode()
        output = io.StringIO(newline="")
        writer = csv.writer(output, lineterminator="\n")
        if header:
            writer.writerow(fields)
        for row in rows:
            writer.writerow([_safe_cell(row.get(f)) for f in fields])
        return output.getvalue().encode()

    @staticmethod
    def _public(row):
        done = row.get("progress_done", 0) or 0
        total = row.get("progress_total")
        percent = (round(min(done, total) * 100 / total, 1) if total else
                   100.0 if row["status"] in {"succeeded", "partial_result"} else 0.0)
        return {k: (plain_json(row[k]) if k == "fields" else
                    utc_text(row[k]) if k in {"created_at", "completed_at", "expires_at"} and row[k]
                    else row[k])
                for k in ("export_id", "manifest_id", "format", "fields", "status", "filename",
                          "row_count", "content_type", "content_sha256", "created_at",
                          "completed_at", "expires_at", "reason", "attempts")
                } | {
                    "cancel_requested": row.get("cancel_requested", False),
                    "progress": {"rows_done": done, "rows_total": total, "percent": percent},
                    "error": ({"code": row.get("error_code"), "message": row.get("error_message")}
                              if row.get("error_code") else None),
                    "download_path": ("/v1/google/exports/" + row["export_id"] + "/content"
                                      if row.get("manifest_id") else None),
                    "cancel_path": ("/v1/google/exports/" + row["export_id"] + "/cancel"
                                    if row["status"] not in TERMINAL else None),
                }

    def _readable(self, principal, row, now, *, content=False):
        if parse_time(now) >= row["expires_at"]:
            raise DomainError("expired", "Export and its frozen manifest have expired", 410)
        self.registry.assert_current(principal, now=now)
        if self._subject(principal) != row["subject_scope"]:
            raise DomainError("not_authorized", "Key/asset rights differ from the frozen export", 403)
        if "status" in row and row["status"] not in {"succeeded", "partial_result"}:
            if content:
                raise DomainError(
                    "precondition_failed",
                    "Export content is not ready in status " + row["status"], 409)
            return
        self.projection._ready(principal, now)
        if not row.get("manifest_id"):
            raise DomainError("source_error", "Completed export lacks a frozen manifest", 503)

    def list(self, principal, parameters, *, now):
        self.projection._ready(principal, now)
        if set(parameters) - {"limit", "cursor"}:
            raise DomainError("invalid_argument", "Unknown export list parameter")
        limit = page_limit(parameters.get("limit"))
        with self.registry.connect() as db:
            self.registry.assert_current(principal, now=now, db=db)
            rows = db.execute("""SELECT e.*,
                                 COALESCE(m.subject_scope,e.subject_scope) AS subject_scope
                                 FROM sf_google_exports e
                                 LEFT JOIN sf_google_export_manifests m
                                 ON m.tenant_id=e.tenant_id AND m.manifest_id=e.manifest_id
                                 WHERE e.tenant_id=%s AND e.expires_at>%s
                                 ORDER BY e.created_at DESC,e.export_id DESC""",
                              (principal.tenant_id, parse_time(now))).fetchall()
        after = None
        binding = dict(tenant_id=principal.tenant_id, rights_version=principal.rights_version,
                       filters={"limit": limit, "subject_scope": self._subject(principal)},
                       sort=["created_at", "export_id"], source="exports:1", manifest_id=None)
        if "cursor" in parameters:
            after = self.projection.cursor_codec.decode(parameters["cursor"], binding=binding, now=now)
        rows = [r for r in rows if self._subject(principal) == r["subject_scope"]]
        selected = [r for r in rows if after is None or
                    (utc_text(r["created_at"]), r["export_id"]) < tuple(after)]
        page, more = selected[:limit], len(selected) > limit
        cursor = None
        if more:
            last = page[-1]
            cursor = self.projection.cursor_codec.encode(
                binding=binding, position=[
                    utc_text(last["created_at"]), last["export_id"]],
                expires_at=min(parse_time(now) + timedelta(minutes=10),
                               min(parse_time(r["expires_at"]) for r in page)), now=now)
        return {"exports": [self._public(r) for r in page], "next_cursor": cursor,
                "status": "synchronous_and_nonblocking_async_export_jobs",
                "worker_state": "external_worker_supported_not_deployed"}

    def detail(self, principal, export_id, *, now):
        with self.registry.connect() as db:
            row = db.execute("""SELECT e.*,
                                COALESCE(m.subject_scope,e.subject_scope) AS subject_scope
                                FROM sf_google_exports e
                                LEFT JOIN sf_google_export_manifests m
                                ON m.tenant_id=e.tenant_id AND m.manifest_id=e.manifest_id
                                WHERE e.tenant_id=%s AND e.export_id=%s""",
                             (principal.tenant_id, export_id)).fetchone()
        if not row:
            raise DomainError("not_found", "No export with this ID", 404)
        self._readable(principal, row, now)
        return self._public(row)

    def content(self, principal, export_id, *, now):
        with self.registry.connect() as db:
            row = db.execute("""SELECT e.*,m.rows,m.evidence,
                                (SELECT count(*) FROM sf_google_export_chunks c
                                 WHERE c.tenant_id=e.tenant_id AND c.export_id=e.export_id) chunks
                                FROM sf_google_exports e
                                LEFT JOIN sf_google_export_manifests m
                                ON m.tenant_id=e.tenant_id AND m.manifest_id=e.manifest_id
                                WHERE e.tenant_id=%s AND e.export_id=%s""",
                             (principal.tenant_id, export_id)).fetchone()
        if not row:
            raise DomainError("not_found", "No export with this ID", 404)
        self._readable(principal, row, now, content=True)
        if row["chunks"]:
            digest = hashlib.sha256()
            parts = []
            with self.registry.connect() as db:
                chunks = db.execute("""SELECT * FROM sf_google_export_chunks
                                       WHERE tenant_id=%s AND export_id=%s
                                       ORDER BY chunk_index""",
                                    (principal.tenant_id, export_id)).fetchall()
            for chunk in chunks:
                inflater = zlib.decompressobj()
                raw = inflater.decompress(chunk["content"], MAX_CHUNK_BYTES + 1)
                if (len(raw) > MAX_CHUNK_BYTES or inflater.unconsumed_tail
                        or not inflater.eof):
                    raise DomainError(
                        "source_error", "Frozen export chunk exceeds its safe bounds", 503)
                if "sha256:" + hashlib.sha256(raw).hexdigest() != chunk["content_sha256"]:
                    raise DomainError(
                        "source_error", "Frozen export chunk does not match its hash", 503)
                digest.update(raw)
                parts.append(raw)
            rendered = b"".join(parts)
            if "sha256:" + digest.hexdigest() != row["content_sha256"]:
                raise DomainError("source_error", "Frozen export content does not match its hash", 503)
        else:
            rendered = self._render(row["rows"], row["fields"], row["format"])
            if "sha256:" + hashlib.sha256(rendered).hexdigest() != row["content_sha256"]:
                raise DomainError("source_error", "Frozen export content does not match its hash", 503)
        # Recheck every frozen version and grants, not merely the stored export hash.
        evidence = row["evidence"]
        frozen_rows = []
        for key in ("keywords", "query_variants", "observations", "features", "items",
                    "export_evidence"):
            frozen_rows.extend(evidence.get(key, []))
        checked = set()
        checked_refs = []
        for frozen in frozen_rows:
            item = frozen.get("evidence"), frozen.get("projection_hash")
            if not all(item):
                raise DomainError("source_error", "Frozen manifest lacks a version/hash reference", 503)
            ref = EvidenceReference(**item[0])
            identity_key = (ref.document_id, ref.document_version, ref.observation_id, item[1])
            if identity_key in checked:
                continue
            checked.add(identity_key)
            checked_refs.append(ref)
            self.projection._rights(principal, ref, use="export", now=now)
            current = self.projection._read_version(principal, ref)
            if self.projection._hash(current) != item[1]:
                raise DomainError("source_error", "Frozen export no longer matches its pinned versions", 503)
        if row["row_count"] and not checked:
            raise DomainError("source_error", "Frozen export has no independently readable evidence", 503)
        # Slow fixed-version reads or rendering may cross a field/evidence
        # deadline. Recheck at completion, not only the request's start time.
        finished=max(parse_time(now),parse_time(self.clock()))
        self._readable(principal,row,finished,content=True)
        for ref in checked_refs:
            self.projection._rights(principal,ref,use='export',now=finished)
        self._readable(principal,row,max(finished,parse_time(self.clock())),content=True)
        return rendered, row["content_type"], row["filename"]

    def _event(self, db, tenant_id, export_id, status, now, detail=None):
        db.execute("""INSERT INTO sf_google_export_events
                      (tenant_id,export_id,status,event_at,detail)
                      VALUES(%s,%s,%s,%s,%s)""",
                   (tenant_id, export_id, status, parse_time(now), Jsonb(detail or {})))

    def cancel(self, principal, export_id, *, now):
        text(export_id, "export_id")
        with self.registry.connect() as db:
            db.execute("SELECT pg_advisory_xact_lock(hashtextextended(%s,20261106))",
                       (principal.tenant_id,))
            self.registry.assert_current(principal, now=now, db=db)
            row = db.execute("""SELECT * FROM sf_google_exports
                                WHERE tenant_id=%s AND export_id=%s FOR UPDATE""",
                             (principal.tenant_id, export_id)).fetchone()
            if not row:
                raise DomainError("not_found", "No export with this ID", 404)
            if row["subject_scope"] != self._subject(principal):
                raise DomainError("not_authorized", "Export belongs to another key", 403)
            if row["status"] in TERMINAL:
                raise DomainError("precondition_failed", "Terminal exports cannot be canceled", 409)
            if row["status"] == "queued":
                db.execute("""UPDATE sf_google_exports SET status='canceled',
                              cancel_requested=true,completed_at=%s,reason='canceled_by_caller'
                              WHERE tenant_id=%s AND export_id=%s""",
                           (parse_time(now), principal.tenant_id, export_id))
                self._event(db, principal.tenant_id, export_id, "canceled", now,
                            {"requested": True})
            else:
                db.execute("""UPDATE sf_google_exports SET cancel_requested=true
                              WHERE tenant_id=%s AND export_id=%s""",
                           (principal.tenant_id, export_id))
                self._event(db, principal.tenant_id, export_id, "cancel_requested", now)
            row = db.execute("""SELECT * FROM sf_google_exports
                                WHERE tenant_id=%s AND export_id=%s""",
                             (principal.tenant_id, export_id)).fetchone()
        return self._public(row)

    def expire_due(self, *, now):
        current = parse_time(now)
        with self.registry.connect() as db:
            rows = db.execute("""UPDATE sf_google_exports SET status='expired',
                                 content=NULL,completed_at=%s,reason='expired',
                                 manifest_id=NULL,worker_ref=NULL,lease_token=NULL,
                                 lease_expires_at=NULL,heartbeat_at=NULL
                                 WHERE expires_at<=%s AND status NOT IN
                                 ('succeeded','partial_result','failed','canceled','expired')
                                 RETURNING tenant_id,export_id""",
                              (current, current)).fetchall()
            for row in rows:
                self._event(db, row["tenant_id"], row["export_id"], "expired", now)
        return len(rows)

    def recover_expired_leases(self, *, now, tenant_id=None):
        current = parse_time(now)
        recovered = 0
        with self.registry.connect() as db:
            params = [current]
            tenant_filter = ""
            if tenant_id is not None:
                text(tenant_id, "tenant_id")
                tenant_filter = " AND tenant_id=%s"
                params.append(tenant_id)
            rows = db.execute(f"""SELECT * FROM sf_google_exports
                                  WHERE status='running' AND lease_expires_at<=%s{tenant_filter}
                                  ORDER BY created_at FOR UPDATE SKIP LOCKED""",
                              tuple(params)).fetchall()
            for row in rows:
                db.execute("""DELETE FROM sf_google_export_chunks
                              WHERE tenant_id=%s AND export_id=%s""",
                           (row["tenant_id"], row["export_id"]))
                if current >= parse_time(row["expires_at"]):
                    status, reason = "expired", "expired"
                elif row["cancel_requested"]:
                    status, reason = "canceled", "canceled_by_caller"
                elif row["attempts"] >= MAX_ATTEMPTS:
                    status, reason = "failed", "worker_lease_exhausted"
                else:
                    status, reason = "queued", None
                if status == "queued":
                    db.execute("""UPDATE sf_google_exports SET status='queued',
                                  reason=NULL,worker_ref=NULL,lease_token=NULL,
                                  lease_expires_at=NULL,heartbeat_at=NULL,
                                  progress_done=0,progress_total=NULL,error_code=NULL,
                                  error_message=NULL WHERE tenant_id=%s AND export_id=%s""",
                               (row["tenant_id"], row["export_id"]))
                else:
                    db.execute("""UPDATE sf_google_exports SET status=%s,reason=%s,
                                  completed_at=%s,worker_ref=NULL,lease_token=NULL,
                                  lease_expires_at=NULL,heartbeat_at=NULL,
                                  error_code=%s,error_message=NULL
                                  WHERE tenant_id=%s AND export_id=%s""",
                               (status, reason, current,
                                "worker_lease_exhausted" if status == "failed" else None,
                                row["tenant_id"], row["export_id"]))
                self._event(db, row["tenant_id"], row["export_id"], "lease_recovered", now,
                            {"outcome": status, "attempts": row["attempts"],
                             "expired_worker_ref": row["worker_ref"]})
                recovered += 1
        return recovered

    def tenant_ids_with_work(self, *, now):
        with self.registry.connect() as db:
            rows = db.execute("""SELECT DISTINCT tenant_id FROM sf_google_exports
                                 WHERE expires_at>%s AND
                                 (status='queued' OR (status='running' AND lease_expires_at<=%s))
                                 ORDER BY tenant_id""",
                              (parse_time(now), parse_time(now))).fetchall()
        return [row["tenant_id"] for row in rows]

    def _heartbeat(self, tenant_id, export_id, lease_token, *, now):
        current = parse_time(now)
        with self.registry.connect() as db:
            row = db.execute("""UPDATE sf_google_exports
                                SET heartbeat_at=%s,lease_expires_at=%s
                                WHERE tenant_id=%s AND export_id=%s AND status='running'
                                  AND lease_token=%s AND lease_expires_at>%s
                                  AND cancel_requested=false AND expires_at>%s
                                RETURNING export_id""",
                             (current, current + timedelta(seconds=LEASE_SECONDS),
                              tenant_id, export_id, lease_token, current, current)).fetchone()
        return bool(row)

    def _progress(self, tenant_id, export_id, lease_token, *, done, total, now):
        current = parse_time(now)
        with self.registry.connect() as db:
            row = db.execute("""UPDATE sf_google_exports
                                SET progress_done=%s,progress_total=%s,heartbeat_at=%s,
                                    lease_expires_at=%s
                                WHERE tenant_id=%s AND export_id=%s AND status='running'
                                  AND lease_token=%s AND lease_expires_at>%s
                                  AND cancel_requested=false AND expires_at>%s
                                RETURNING export_id""",
                             (done, total, current, current + timedelta(seconds=LEASE_SECONDS),
                              tenant_id, export_id, lease_token, current, current)).fetchone()
        return bool(row)

    def _stop_if_interrupted(self, tenant_id, export_id, lease_token, *, now):
        current = parse_time(now)
        with self.registry.connect() as db:
            row = db.execute("""SELECT * FROM sf_google_exports
                                WHERE tenant_id=%s AND export_id=%s FOR UPDATE""",
                             (tenant_id, export_id)).fetchone()
            if not row or row["lease_token"] != lease_token or row["status"] != "running":
                return False
            if row["cancel_requested"]:
                status, reason = "canceled", "canceled_by_caller"
            elif current >= parse_time(row["expires_at"]):
                status, reason = "expired", "expired"
            else:
                return False
            db.execute("""DELETE FROM sf_google_export_chunks
                          WHERE tenant_id=%s AND export_id=%s""",
                       (tenant_id, export_id))
            db.execute("""UPDATE sf_google_exports SET status=%s,reason=%s,
                          manifest_id=NULL,content_sha256=NULL,completed_at=%s,
                          progress_total=0,worker_ref=NULL,lease_token=NULL,
                          lease_expires_at=NULL,heartbeat_at=NULL
                          WHERE tenant_id=%s AND export_id=%s""",
                       (status, reason, current, tenant_id, export_id))
            self._event(db, tenant_id, export_id, status, now, {"reason": reason})
        return True

    def _rights_snapshot(self, principal, rows, *, now, seen, output):
        for row in rows:
            evidence = row.get("evidence")
            if not evidence:
                raise DomainError("source_error", "Frozen row lacks a licensed evidence reference", 503)
            ref = EvidenceReference(**evidence)
            self.projection._rights(principal, ref, use="export", now=now)
            if ref.grant_id not in seen:
                seen.add(ref.grant_id)
                grant = self.registry.grant(principal.tenant_id, ref.grant_id)
                output.append({
                    "grant_id": grant.grant_id, "grant_version": grant.version,
                    "asset_id": grant.asset_id, "source_adapter": grant.source_adapter,
                    "source_version": grant.source_version, "allowed_uses": sorted(grant.uses),
                    "fields": sorted(ref.fields), "expires_at": utc_text(grant.expires_at),
                })

    @staticmethod
    def _frozen_evidence(rows):
        return [{"evidence": row["evidence"], "projection_hash": row["projection_hash"]}
                for row in rows]

    def _finish_export(self, *, tenant_id, export_id, lease_token, manifest, rows, status,
                       reason, digest, expiry, now):
        current = parse_time(now)
        with self.registry.connect() as db:
            job = db.execute("""SELECT * FROM sf_google_exports
                                WHERE tenant_id=%s AND export_id=%s FOR UPDATE""",
                             (tenant_id, export_id)).fetchone()
            if not job or job["lease_token"] != lease_token or job["status"] != "running":
                return self._public(job) if job else None
            final_status = status
            if job["cancel_requested"]:
                final_status, reason = "canceled", "canceled_by_caller"
            if current >= parse_time(job["expires_at"]) or expiry <= current:
                final_status, reason = "expired", "expired"
            if final_status in {"canceled", "expired"}:
                db.execute("""DELETE FROM sf_google_export_chunks
                              WHERE tenant_id=%s AND export_id=%s""",
                           (tenant_id, export_id))
                db.execute("""UPDATE sf_google_exports SET status=%s,reason=%s,
                              manifest_id=NULL,content_sha256=NULL,completed_at=%s,
                              progress_total=0,worker_ref=NULL,lease_token=NULL,
                              lease_expires_at=NULL,heartbeat_at=NULL
                              WHERE tenant_id=%s AND export_id=%s""",
                           (final_status, reason, current, tenant_id, export_id))
            else:
                if manifest is None:
                    raise DomainError("source_error", "Completed export lacks a manifest")
                db.execute("""INSERT INTO sf_google_export_manifests
                              VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)
                              ON CONFLICT(tenant_id,manifest_id) DO NOTHING""",
                           (tenant_id, manifest["manifest_id"], job["created_at"], expiry,
                            job["subject_scope"], manifest["projection_revision"],
                            manifest["source_path"], Jsonb(manifest["filters"]),
                            Jsonb(manifest["method_versions"]), Jsonb(manifest["rights_at_query"]),
                            job["request_hash"], Jsonb([]), Jsonb(manifest["evidence"])))
                db.execute("""UPDATE sf_google_exports SET status=%s,manifest_id=%s,
                              row_count=%s,content_sha256=%s,completed_at=%s,expires_at=%s,
                              reason=%s,progress_done=%s,progress_total=%s,worker_ref=NULL,
                              lease_token=NULL,lease_expires_at=NULL,heartbeat_at=NULL,
                              error_code=NULL,error_message=NULL
                              WHERE tenant_id=%s AND export_id=%s""",
                           (final_status, manifest["manifest_id"], len(rows), digest,
                            current, expiry, reason, len(rows), len(rows), tenant_id, export_id))
            self._event(db, tenant_id, export_id, final_status, now,
                        {"reason": reason} if reason else {})
            row = db.execute("""SELECT * FROM sf_google_exports
                                WHERE tenant_id=%s AND export_id=%s""",
                             (tenant_id, export_id)).fetchone()
        return self._public(row)

    def _fail(self, *, tenant_id, export_id, lease_token, code, message, now):
        current = parse_time(now)
        with self.registry.connect() as db:
            row = db.execute("""UPDATE sf_google_exports SET status='failed',
                                error_code=%s,error_message=%s,completed_at=%s,
                                worker_ref=NULL,lease_token=NULL,lease_expires_at=NULL,
                                heartbeat_at=NULL WHERE tenant_id=%s AND export_id=%s
                                AND status='running' AND lease_token=%s
                                RETURNING export_id""",
                             (code, message, current, tenant_id, export_id, lease_token)).fetchone()
            if row:
                db.execute("""DELETE FROM sf_google_export_chunks
                              WHERE tenant_id=%s AND export_id=%s""",
                           (tenant_id, export_id))
                self._event(db, tenant_id, export_id, "failed", now,
                            {"error": {"code": code, "message": message}})
        return bool(row)

    def run_once(self, *, tenant_id, worker_ref, now):
        """Claim and execute one asynchronous export for a separate worker."""
        text(tenant_id, "tenant_id")
        text(worker_ref, "worker_ref")
        self.recover_expired_leases(now=now, tenant_id=tenant_id)
        token = uuid4().hex
        with self.registry.connect() as db:
            db.execute("SELECT pg_advisory_xact_lock(hashtextextended(%s,20261109))",
                       (tenant_id,))
            job = db.execute("""SELECT * FROM sf_google_exports
                                WHERE tenant_id=%s AND status='queued'
                                  AND cancel_requested=false AND expires_at>%s
                                ORDER BY created_at FOR UPDATE SKIP LOCKED LIMIT 1""",
                             (tenant_id, parse_time(now))).fetchone()
            if not job:
                return None
            db.execute("""UPDATE sf_google_exports SET status='running',started_at=%s,
                          worker_ref=%s,lease_token=%s,lease_expires_at=%s,heartbeat_at=%s,
                          attempts=attempts+1,progress_done=0,progress_total=NULL,
                          error_code=NULL,error_message=NULL,reason=NULL
                          WHERE tenant_id=%s AND export_id=%s""",
                       (parse_time(now), worker_ref, token,
                        parse_time(now) + timedelta(seconds=LEASE_SECONDS), parse_time(now),
                        tenant_id, job["export_id"]))
            db.execute("""DELETE FROM sf_google_export_chunks
                          WHERE tenant_id=%s AND export_id=%s""",
                       (tenant_id, job["export_id"]))
            self._event(db, tenant_id, job["export_id"], "running", now,
                        {"worker_ref": worker_ref})
        try:
            principal = self.registry.principal(
                tenant_id, now=now, subject_ref=job["subject_ref"])
            if not principal.grant_ids or self._subject(principal) != job["subject_scope"]:
                raise DomainError("not_authorized", "Export owner rights changed", 403)
            request = plain_json(job["request"])
            expanded, read_filters, key = self._read_route(
                request["source_path"], request["filters"])
            fields, fmt = request["fields"], request["format"]
            cursor, chunk_index, total_rows = None, 0, 0
            overall = hashlib.sha256()
            rights, seen = [], set()
            frozen, analysis_items = [], []
            evidence_expiry, revision, projection_version = None, None, None
            terminal_reason, terminal_status = None, "succeeded"
            while True:
                if not self._heartbeat(tenant_id, job["export_id"], token, now=now):
                    self._stop_if_interrupted(
                        tenant_id, job["export_id"], token, now=now)
                    current = self.detail(principal, job["export_id"], now=now)
                    return current
                params = dict(read_filters, limit=str(PAGE_SIZE))
                if cursor:
                    params["cursor"] = cursor
                page = self.projection.read(principal, expanded, params, now=now)
                rows = page[key]
                page_revision = page["projection_revision"]
                if revision is None:
                    revision, projection_version = page_revision, page["projection_version"]
                elif revision != page_revision:
                    raise DomainError(
                        "precondition_failed",
                        "Projection changed during asynchronous export", 412)
                if page["evidence_expires_at"]:
                    deadline = parse_time(page["evidence_expires_at"])
                    evidence_expiry = min(evidence_expiry, deadline) if evidence_expiry else deadline
                if total_rows + len(rows) > MAX_EXPORT_ROWS:
                    rows = rows[:MAX_EXPORT_ROWS - total_rows]
                    terminal_status = "partial_result"
                    terminal_reason = "row_limit_exceeded"
                self._rights_snapshot(
                    principal, rows, now=now, seen=seen, output=rights)
                if rows:
                    rendered = self._render(
                        rows, fields, fmt, header=(fmt == "csv" and chunk_index == 0))
                    packed = zlib.compress(rendered)
                    chunk_hash = "sha256:" + hashlib.sha256(rendered).hexdigest()
                    with self.registry.connect() as db:
                        db.execute("""INSERT INTO sf_google_export_chunks
                                      VALUES(%s,%s,%s,%s,'zlib',%s,%s,%s)""",
                                   (tenant_id, job["export_id"], chunk_index, len(rows),
                                    packed, chunk_hash, parse_time(now)))
                    overall.update(rendered)
                    frozen.extend(self._frozen_evidence(rows))
                    if request["source_path"] == "/observations/{id}/items":
                        analysis_items.extend({
                            name: row.get(name) for name in
                            ("item_id", "result_type", "organic_position", "target_url",
                             "evidence", "projection_hash")
                        } for row in rows)
                    chunk_index += 1
                    total_rows += len(rows)
                total = total_rows if terminal_status == "partial_result" else None
                if not self._progress(
                        tenant_id, job["export_id"], token,
                        done=total_rows, total=total, now=now):
                    self._stop_if_interrupted(
                        tenant_id, job["export_id"], token, now=now)
                    current = self.detail(principal, job["export_id"], now=now)
                    return current
                cursor = page["next_cursor"]
                if terminal_status == "partial_result" or not cursor:
                    break
            if terminal_status == "succeeded" and total_rows == 0:
                # A true empty result remains an explicit successful frozen file.
                evidence_expiry = parse_time(now) + timedelta(hours=24)
            expiry = min(parse_time(job["expires_at"]),
                         evidence_expiry or parse_time(now) + timedelta(hours=24))
            manifest_id = identity("async-export-manifest", {
                "tenant_id": tenant_id, "export_id": job["export_id"],
                "request_hash": job["request_hash"], "projection_revision": revision,
                "chunks": chunk_index, "row_count": total_rows,
                "content_sha256": "sha256:" + overall.hexdigest(),
            })
            manifest = {
                "manifest_id": manifest_id, "projection_revision": revision,
                "source_path": request["source_path"], "filters": request["filters"],
                "method_versions": {
                    "projection": projection_version, "export": "2",
                    "delivery": "queued_chunked",
                },
                "rights_at_query": rights,
                "evidence": {
                    "export_evidence": frozen,
                    "items": analysis_items,
                },
            }
            row = self._finish_export(
                tenant_id=tenant_id, export_id=job["export_id"], lease_token=token,
                manifest=manifest, rows=range(total_rows), status=terminal_status,
                reason=terminal_reason,
                digest="sha256:" + overall.hexdigest(), expiry=expiry, now=now)
            return row
        except DomainError as exc:
            self._fail(tenant_id=tenant_id, export_id=job["export_id"], lease_token=token,
                       code=exc.code, message=str(exc), now=now)
            current = self.detail(self.registry.principal(
                tenant_id, now=now, subject_ref=job["subject_ref"]),
                job["export_id"], now=now)
            return current
        except Exception:
            self._fail(tenant_id=tenant_id, export_id=job["export_id"], lease_token=token,
                       code="source_error", message="Async export worker failed", now=now)
            current = self.detail(self.registry.principal(
                tenant_id, now=now, subject_ref=job["subject_ref"]),
                job["export_id"], now=now)
            return current

    def manifest_snapshot(self, principal, manifest_id, *, now):
        """Return the frozen, licensed snapshot for a follow-on analysis job."""
        text(manifest_id, "manifest_id")
        with self.registry.connect() as db:
            row = db.execute("""SELECT * FROM sf_google_export_manifests
                                WHERE tenant_id=%s AND manifest_id=%s""",
                             (principal.tenant_id, manifest_id)).fetchone()
        if not row:
            raise DomainError("not_found", "No frozen manifest with this ID", 404)
        self._readable(principal, row, now)
        return row

    def purge_expired(self, *, now):
        with self.registry.connect() as db:
            rows = db.execute("DELETE FROM sf_google_exports WHERE expires_at<=%s RETURNING tenant_id",
                              (parse_time(now),)).fetchall()
            db.execute("DELETE FROM sf_google_export_manifests WHERE expires_at<=%s", (parse_time(now),))
        return len(rows)


class ExportWorker:
    """Separate-process polling loop for queued chunked exports."""

    def __init__(self, service, *, worker_ref, clock=None, poll_seconds=1.0):
        self.service = service
        self.worker_ref = worker_ref
        self.clock = clock or _clock
        self.poll_seconds = max(0.1, float(poll_seconds))
        self.stop = threading.Event()

    def run_once(self, *, now=None):
        current = now or self.clock()
        self.service.expire_due(now=current)
        self.service.recover_expired_leases(now=current)
        for tenant_id in self.service.tenant_ids_with_work(now=current):
            result = self.service.run_once(
                tenant_id=tenant_id, worker_ref=self.worker_ref, now=current)
            if result is not None:
                return result
        return None

    def run_forever(self):
        while not self.stop.wait(self.poll_seconds):
            self.run_once()
