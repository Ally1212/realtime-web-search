"""Immutable, permission-revalidated exports from a frozen projection snapshot.

Rows are selected facts already licensed for derived storage; no raw source response,
article body, credential or second raw fact store is written. This is synchronous and
small-scope only. The public asynchronous job contract and large/million-row export
path are not implemented by this module.
"""
