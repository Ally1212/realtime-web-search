"""Durable analysis-job state machine over frozen manifests.

No worker is started by the web process and no source call is made here. A
separately deployed worker may claim jobs; queued is never reported as success.
The synchronous small analysis is limited to selected items already frozen by
an export manifest.
"""
from __future__ import annotations

from collections import Counter
from datetime import datetime, timedelta, timezone
import re
import threading
from uuid import uuid4

import psycopg
from psycopg.errors import UniqueViolation
from psycopg.types.json import Jsonb

from .google_domain import DomainError, canonical_json, identity, parse_time, plain_json, text, utc_text
from .google_evidence import EvidenceReference, page_limit

SCHEMA = """
CREATE TABLE IF NOT EXISTS sf_google_analysis_jobs (
 tenant_id text NOT NULL, job_id text NOT NULL, idempotency_key text NOT NULL,
 request_hash text NOT NULL, manifest_id text NOT NULL, analysis_type text NOT NULL,
 subject_ref text NOT NULL, status text NOT NULL,
 created_at timestamptz NOT NULL, expires_at timestamptz NOT NULL,
 started_at timestamptz, completed_at timestamptz, cancel_requested boolean NOT NULL DEFAULT false,
 worker_ref text, lease_token text, lease_expires_at timestamptz, heartbeat_at timestamptz,
 attempts integer NOT NULL DEFAULT 0, progress_done integer NOT NULL DEFAULT 0,
 progress_total integer NOT NULL DEFAULT 0, partial_result jsonb,
 result jsonb, error_code text, error_message text,
 PRIMARY KEY(tenant_id,job_id), UNIQUE(tenant_id,idempotency_key)
);
CREATE INDEX IF NOT EXISTS sf_google_analysis_jobs_queue
 ON sf_google_analysis_jobs(tenant_id,status,created_at);
CREATE TABLE IF NOT EXISTS sf_google_analysis_job_events (
 tenant_id text NOT NULL, job_id text NOT NULL, seq bigint GENERATED BY DEFAULT AS IDENTITY,
 status text NOT NULL, event_at timestamptz NOT NULL, detail jsonb NOT NULL,
 PRIMARY KEY(tenant_id,job_id,seq),
 FOREIGN KEY(tenant_id,job_id) REFERENCES sf_google_analysis_jobs ON DELETE CASCADE
);
"""

MIGRATIONS = """
ALTER TABLE sf_google_analysis_jobs
 ADD COLUMN IF NOT EXISTS heartbeat_at timestamptz,
 ADD COLUMN IF NOT EXISTS attempts integer NOT NULL DEFAULT 0,
 ADD COLUMN IF NOT EXISTS progress_done integer NOT NULL DEFAULT 0,
 ADD COLUMN IF NOT EXISTS progress_total integer NOT NULL DEFAULT 0,
 ADD COLUMN IF NOT EXISTS partial_result jsonb;
"""

TERMINAL = frozenset({"succeeded", "failed", "canceled", "expired"})
TYPES = frozenset({"item-coverage", "rank-summary"})
LEASE_SECONDS = 300
MAX_ATTEMPTS = 3
PROGRESS_STEP = 25


def _now():
    return datetime.now(timezone.utc)


def _job_id(tenant_id, key):
    return identity("analysis-job", {"tenant_id": tenant_id, "idempotency_key": key})


class AnalysisJobService:
    def __init__(self, dsn, *, registry, manifests, clock=None):
        self.dsn, self.registry, self.manifests = dsn, registry, manifests
        self.clock = clock or _now

    def initialize(self):
        with self.registry.connect() as db:
            db.execute("SELECT pg_advisory_xact_lock(20261104,7)")
            db.execute(SCHEMA)
            db.execute(MIGRATIONS)

    @staticmethod
    def route(path):
        if path in {"/analysis-jobs", "/analysis-jobs/"}:
            return "list", None
        match = re.fullmatch(r"/analysis-jobs/([^/]+)(/cancel)?", path)
        if match:
            return ("cancel" if match[2] else "detail"), match[1]
        raise DomainError("not_found", "No analysis job route matches", 404)

    def _public(self, row, *, now, include_result=True):
        expired = parse_time(now) >= parse_time(row["expires_at"])
        status = "expired" if expired and row["status"] not in TERMINAL else row["status"]
        result = None if expired or not include_result else plain_json(row["result"])
        total = row.get("progress_total", 0) or 0
        done = row.get("progress_done", 0) or 0
        percent = (round(min(done, total) * 100 / total, 1) if total else
                   100.0 if status == "succeeded" else 0.0)
        return {
            "job_id": row["job_id"], "manifest_id": row["manifest_id"],
            "analysis_type": row["analysis_type"], "status": status,
            "cancel_requested": row["cancel_requested"],
            "created_at": utc_text(row["created_at"]), "expires_at": utc_text(row["expires_at"]),
            "started_at": utc_text(row["started_at"]) if row["started_at"] else None,
            "completed_at": utc_text(row["completed_at"]) if row["completed_at"] else None,
            "attempts": row.get("attempts", 0),
            "progress": {"done": done, "total": total, "percent": percent},
            "partial_result": plain_json(row.get("partial_result")),
            "result": result, "error": ({"code": row["error_code"], "message": row["error_message"]}
                                         if row["error_code"] else None),
            "execution": "queued_not_started" if status == "queued" else
                         "worker_required" if status == "running" else "terminal",
        }

    def _event(self, db, tenant, job_id, status, now, detail=None):
        db.execute("""INSERT INTO sf_google_analysis_job_events
                      (tenant_id,job_id,status,event_at,detail) VALUES(%s,%s,%s,%s,%s)""",
                   (tenant, job_id, status, parse_time(now), Jsonb(detail or {})))

    def _manifest(self, principal, manifest_id, now):
        return self.manifests.manifest_snapshot(principal, manifest_id, now=now)

    def _validate_manifest(self, principal, manifest, *, now, progress=None):
        evidence = manifest["evidence"] or {}
        rows = evidence.get("items")
        if not isinstance(rows, list):
            raise DomainError("invalid_argument", "Analysis requires a frozen observation-items manifest", 400)
        if progress:
            progress(0, len(rows))
        for index, row in enumerate(rows, 1):
            if (not isinstance(row, dict) or not isinstance(row.get("result_type"), str)
                    or not row.get("result_type").strip()):
                raise DomainError("invalid_argument", "Frozen items lack a typed result occurrence", 400)
            if not row.get("item_id"):
                raise DomainError("invalid_argument", "Frozen items lack stable item IDs", 400)
            evidence = row.get("evidence")
            if not evidence:
                raise DomainError("source_error", "Frozen items lack evidence references", 503)
            self.manifests.projection._rights(
                principal, EvidenceReference(**evidence), use="aggregate", now=now)
            if progress and (index % PROGRESS_STEP == 0 or index == len(rows)):
                progress(index, len(rows))
        return rows

    def create(self, principal, body, *, idempotency_key, now):
        text(idempotency_key, "Idempotency-Key", maximum=120)
        if not isinstance(body, dict) or set(body) != {"manifest_id", "analysis_type"}:
            raise DomainError("invalid_argument", "Analysis body requires manifest_id and analysis_type")
        manifest_id, analysis_type = body["manifest_id"], body["analysis_type"]
        text(manifest_id, "manifest_id")
        if analysis_type not in TYPES:
            raise DomainError("unsupported", "Unknown deterministic analysis type", 400)
        request_hash = identity("analysis-request", {
            "manifest_id": manifest_id, "analysis_type": analysis_type})
        with self.registry.connect() as db:
            existing = db.execute("SELECT * FROM sf_google_analysis_jobs WHERE tenant_id=%s AND idempotency_key=%s",
                                  (principal.tenant_id, idempotency_key)).fetchone()
        if existing:
            if existing["request_hash"] != request_hash:
                raise DomainError("idempotency_conflict", "Idempotency key was used for another analysis job", 409)
            return self.detail(principal, existing["job_id"], now=now)
        manifest = self._manifest(principal, manifest_id, now)
        self._validate_manifest(principal, manifest, now=now)
        expiry = parse_time(manifest["expires_at"])
        if expiry <= parse_time(now):
            raise DomainError("expired", "Manifest evidence has expired", 410)
        job_id = _job_id(principal.tenant_id, idempotency_key)
        try:
            with self.registry.connect() as db:
                db.execute("SELECT pg_advisory_xact_lock(hashtextextended(%s,20261107))",
                           (principal.tenant_id,))
                self.registry.assert_current(principal, now=now, db=db)
                conflict = db.execute("SELECT * FROM sf_google_analysis_jobs "
                                      "WHERE tenant_id=%s AND idempotency_key=%s",
                                      (principal.tenant_id, idempotency_key)).fetchone()
                if conflict:
                    if conflict["request_hash"] != request_hash:
                        raise DomainError("idempotency_conflict",
                                          "Idempotency key was used for another analysis job", 409)
                    return self._public(conflict, now=now)
                db.execute("""INSERT INTO sf_google_analysis_jobs
                    (tenant_id,job_id,idempotency_key,request_hash,manifest_id,analysis_type,
                     subject_ref,status,created_at,expires_at)
                    VALUES(%s,%s,%s,%s,%s,%s,%s,'queued',%s,%s)""",
                           (principal.tenant_id, job_id, idempotency_key, request_hash, manifest_id,
                            analysis_type, principal.subject_ref, parse_time(now), expiry))
                self._event(db, principal.tenant_id, job_id, "queued", now,
                            {"analysis_type": analysis_type})
                row = db.execute("SELECT * FROM sf_google_analysis_jobs WHERE tenant_id=%s AND job_id=%s",
                                 (principal.tenant_id, job_id)).fetchone()
            return self._public(row, now=now)
        except UniqueViolation:
            with self.registry.connect() as db:
                row = db.execute("SELECT * FROM sf_google_analysis_jobs WHERE tenant_id=%s AND idempotency_key=%s",
                                 (principal.tenant_id, idempotency_key)).fetchone()
            if not row or row["request_hash"] != request_hash:
                raise DomainError("idempotency_conflict", "Idempotency race with another request", 409) from None
            return self.detail(principal, row["job_id"], now=now)

    def detail(self, principal, job_id, *, now):
        text(job_id, "job_id")
        with self.registry.connect() as db:
            row = db.execute("SELECT * FROM sf_google_analysis_jobs WHERE tenant_id=%s AND job_id=%s",
                             (principal.tenant_id, job_id)).fetchone()
        if not row:
            raise DomainError("not_found", "No analysis job with this ID", 404)
        if row["subject_ref"] != principal.subject_ref and "manager" not in principal.roles:
            raise DomainError("not_authorized", "Analysis job belongs to another key", 403)
        if parse_time(now) >= parse_time(row["expires_at"]):
            return self._public(row, now=now)
        manifest = self.manifests.manifest_snapshot(principal, row["manifest_id"], now=now)
        if row["status"] == "succeeded":
            self._validate_manifest(principal, manifest, now=now)
        return self._public(row, now=now)

    def list(self, principal, parameters, *, now):
        if set(parameters) - {"limit", "cursor"}:
            raise DomainError("invalid_argument", "Unknown analysis job list parameter")
        limit = page_limit(parameters.get("limit"))
        after = None
        binding = dict(tenant_id=principal.tenant_id, rights_version=principal.rights_version,
                       filters={"limit": limit, "subject": principal.subject_ref},
                       sort=["created_at", "job_id"], source="analysis-jobs:1", manifest_id=None)
        if "cursor" in parameters:
            after = self.manifests.projection.cursor_codec.decode(parameters["cursor"], binding=binding, now=now)
        with self.registry.connect() as db:
            rows = db.execute("""SELECT * FROM sf_google_analysis_jobs
                                 WHERE tenant_id=%s AND subject_ref=%s
                                 ORDER BY created_at DESC,job_id DESC""",
                              (principal.tenant_id, principal.subject_ref)).fetchall()
        rows = [r for r in rows if parse_time(now) < parse_time(r["expires_at"])
                or r["status"] in TERMINAL]
        if after is not None:
            rows = [r for r in rows if (utc_text(r["created_at"]), r["job_id"]) < tuple(after)]
        page, more = rows[:limit], len(rows) > limit
        cursor = None
        if more:
            last = page[-1]
            cursor = self.manifests.projection.cursor_codec.encode(
                binding=binding, position=[utc_text(last["created_at"]), last["job_id"]],
                expires_at=min(parse_time(now) + timedelta(minutes=10),
                               min(parse_time(r["expires_at"]) for r in page)), now=now)
        return {"jobs": [self._public(r, now=now, include_result=False) for r in page], "next_cursor": cursor,
                "worker_state": "external_worker_supported_not_deployed",
                "queued_is_not_success": True}

    def cancel(self, principal, job_id, *, now):
        text(job_id, "job_id")
        with self.registry.connect() as db:
            db.execute("SELECT pg_advisory_xact_lock(hashtextextended(%s,20261107))",
                       (principal.tenant_id,))
            self.registry.assert_current(principal, now=now, db=db)
            row = db.execute("SELECT * FROM sf_google_analysis_jobs WHERE tenant_id=%s AND job_id=%s FOR UPDATE",
                             (principal.tenant_id, job_id)).fetchone()
            if not row:
                raise DomainError("not_found", "No analysis job with this ID", 404)
            if row["subject_ref"] != principal.subject_ref and "manager" not in principal.roles:
                raise DomainError("not_authorized", "Analysis job belongs to another key", 403)
            if row["status"] in TERMINAL:
                raise DomainError("precondition_failed", "Terminal analysis jobs cannot be canceled", 409)
            if row["status"] == "queued":
                db.execute("""UPDATE sf_google_analysis_jobs SET status='canceled',
                              cancel_requested=true,completed_at=%s WHERE tenant_id=%s AND job_id=%s""",
                           (parse_time(now), principal.tenant_id, job_id))
                self._event(db, principal.tenant_id, job_id, "canceled", now, {"requested": True})
            else:
                db.execute("""UPDATE sf_google_analysis_jobs SET cancel_requested=true
                              WHERE tenant_id=%s AND job_id=%s""", (principal.tenant_id, job_id))
                self._event(db, principal.tenant_id, job_id, "cancel_requested", now)
            row = db.execute("SELECT * FROM sf_google_analysis_jobs WHERE tenant_id=%s AND job_id=%s",
                             (principal.tenant_id, job_id)).fetchone()
        return self._public(row, now=now)

    def expire_due(self, *, now):
        with self.registry.connect() as db:
            rows = db.execute("""UPDATE sf_google_analysis_jobs SET status='expired',result=NULL,
                                 completed_at=%s WHERE expires_at<=%s AND status NOT IN
                                 ('succeeded','failed','canceled','expired') RETURNING tenant_id,job_id""",
                              (parse_time(now), parse_time(now))).fetchall()
            for row in rows:
                self._event(db, row["tenant_id"], row["job_id"], "expired", now)
        return len(rows)

    def heartbeat(self, tenant_id, job_id, lease_token, *, now):
        """Renew a live worker lease; stale tokens cannot resurrect a job."""
        text(tenant_id, "tenant_id")
        text(job_id, "job_id")
        text(lease_token, "lease_token")
        current = parse_time(now)
        with self.registry.connect() as db:
            row = db.execute("""UPDATE sf_google_analysis_jobs
                                SET heartbeat_at=%s,lease_expires_at=%s
                                WHERE tenant_id=%s AND job_id=%s AND status='running'
                                  AND lease_token=%s AND lease_expires_at>%s
                                  AND cancel_requested=false AND expires_at>%s
                                RETURNING job_id""",
                             (current, current + timedelta(seconds=LEASE_SECONDS), tenant_id,
                              job_id, lease_token, current, current)).fetchone()
        return bool(row)

    def recover_expired_leases(self, *, now, tenant_id=None):
        """Requeue crashed work or terminally fail attempts to avoid an endless loop."""
        current = parse_time(now)
        recovered = 0
        with self.registry.connect() as db:
            params = [current]
            tenant_filter = ""
            if tenant_id is not None:
                text(tenant_id, "tenant_id")
                tenant_filter = " AND tenant_id=%s"
                params.append(tenant_id)
            rows = db.execute(f"""SELECT * FROM sf_google_analysis_jobs
                                  WHERE status='running' AND lease_expires_at<=%s{tenant_filter}
                                  ORDER BY created_at FOR UPDATE SKIP LOCKED""",
                              tuple(params)).fetchall()
            for row in rows:
                if current >= parse_time(row["expires_at"]):
                    status, error_code, error_message = "expired", None, None
                elif row["cancel_requested"]:
                    status, error_code, error_message = "canceled", None, None
                elif row["attempts"] >= MAX_ATTEMPTS:
                    status = "failed"
                    error_code = "worker_lease_exhausted"
                    error_message = "Worker lease expired after the maximum attempts"
                else:
                    status, error_code, error_message = "queued", None, None
                if status == "queued":
                    db.execute("""UPDATE sf_google_analysis_jobs SET status='queued',
                                  worker_ref=NULL,lease_token=NULL,lease_expires_at=NULL,
                                  heartbeat_at=NULL,progress_done=0,partial_result=NULL
                                  WHERE tenant_id=%s AND job_id=%s""",
                               (row["tenant_id"], row["job_id"]))
                else:
                    db.execute("""UPDATE sf_google_analysis_jobs SET status=%s,result=NULL,
                                  partial_result=NULL,error_code=%s,error_message=%s,
                                  completed_at=%s,worker_ref=NULL,lease_token=NULL,
                                  lease_expires_at=NULL,heartbeat_at=NULL
                                  WHERE tenant_id=%s AND job_id=%s""",
                               (status, error_code, error_message, current,
                                row["tenant_id"], row["job_id"]))
                self._event(db, row["tenant_id"], row["job_id"], "lease_recovered", now,
                            {"outcome": status, "attempts": row["attempts"],
                             "expired_worker_ref": row["worker_ref"]})
                recovered += 1
        return recovered

    def tenant_ids_with_work(self, *, now):
        with self.registry.connect() as db:
            rows = db.execute("""SELECT DISTINCT tenant_id FROM sf_google_analysis_jobs
                                 WHERE expires_at>%s AND
                                 (status='queued' OR (status='running' AND lease_expires_at<=%s))
                                 ORDER BY tenant_id""",
                              (parse_time(now), parse_time(now))).fetchall()
        return [row["tenant_id"] for row in rows]

    def _progress(self, tenant_id, job_id, lease_token, *, done, total, now, partial=None):
        with self.registry.connect() as db:
            row = db.execute("""UPDATE sf_google_analysis_jobs
                                SET progress_done=%s,progress_total=%s,partial_result=%s,
                                    heartbeat_at=%s,lease_expires_at=%s
                                WHERE tenant_id=%s AND job_id=%s AND status='running'
                                  AND lease_token=%s AND lease_expires_at>%s
                                  AND cancel_requested=false AND expires_at>%s
                                RETURNING job_id""",
                             (done, total, Jsonb(partial) if partial is not None else None,
                              parse_time(now), parse_time(now) + timedelta(seconds=LEASE_SECONDS),
                              tenant_id, job_id, lease_token, parse_time(now),
                              parse_time(now))).fetchone()
        return bool(row)

    def run_once(self, *, tenant_id, worker_ref, now):
        """Claim and run one queued job. Must be invoked by a separate worker."""
        text(tenant_id, "tenant_id")
        text(worker_ref, "worker_ref")
        self.recover_expired_leases(now=now, tenant_id=tenant_id)
        token, job = uuid4().hex, None
        with self.registry.connect() as db:
            db.execute("SELECT pg_advisory_xact_lock(hashtextextended(%s,20261108))", (tenant_id,))
            job = db.execute("""SELECT * FROM sf_google_analysis_jobs
                                WHERE tenant_id=%s AND status='queued'
                                AND cancel_requested=false AND expires_at>%s
                                ORDER BY created_at FOR UPDATE SKIP LOCKED LIMIT 1""",
                             (tenant_id, parse_time(now))).fetchone()
            if job:
                db.execute("""UPDATE sf_google_analysis_jobs SET status='running',started_at=%s,
                              worker_ref=%s,lease_token=%s,lease_expires_at=%s,heartbeat_at=%s,
                              attempts=attempts+1,progress_done=0,progress_total=0,partial_result=NULL
                              WHERE tenant_id=%s AND job_id=%s""",
                           (parse_time(now), worker_ref, token,
                            parse_time(now) + timedelta(seconds=LEASE_SECONDS), parse_time(now),
                            tenant_id, job["job_id"]))
                self._event(db, tenant_id, job["job_id"], "running", now, {"worker_ref": worker_ref})
        if not job:
            return None
        try:
            principal = self.registry.principal(tenant_id, now=now, subject_ref=job["subject_ref"])
            if not principal.grant_ids:
                raise DomainError("not_authorized", "Job owner has no current asset grant", 403)
            manifest = self._manifest(principal, job["manifest_id"], now)
            rows = self._validate_manifest(
                principal, manifest, now=now,
                progress=lambda done, total: self._progress(
                    tenant_id, job["job_id"], token, done=done, total=total, now=now))
            result = self._analyze(job["analysis_type"], rows)
            final_status, error = "succeeded", None
        except DomainError as exc:
            final_status, result = "expired" if exc.code == "expired" else "failed", None
            error = {"code": exc.code, "message": str(exc)}
        except Exception:
            final_status, result = "failed", None
            error = {"code": "source_error", "message": "Analysis worker failed"}
        with self.registry.connect() as db:
            current = db.execute("""SELECT * FROM sf_google_analysis_jobs
                                    WHERE tenant_id=%s AND job_id=%s FOR UPDATE""",
                                 (tenant_id, job["job_id"])).fetchone()
            if not current or current["lease_token"] != token or current["status"] != "running":
                return self._public(current, now=now) if current else None
            if current["cancel_requested"]:
                final_status, result, error = "canceled", None, None
            if parse_time(now) >= parse_time(current["expires_at"]):
                final_status, result, error = "expired", None, None
            db.execute("""UPDATE sf_google_analysis_jobs SET status=%s,result=%s,error_code=%s,
                          error_message=%s,completed_at=%s,lease_expires_at=NULL,heartbeat_at=NULL,
                          progress_done=CASE WHEN %s='succeeded' THEN progress_total ELSE progress_done END,
                          partial_result=NULL
                          WHERE tenant_id=%s AND job_id=%s""",
                       (final_status, Jsonb(result) if result is not None else None,
                        error["code"] if error else None, error["message"] if error else None,
                        parse_time(now), final_status, tenant_id, job["job_id"]))
            self._event(db, tenant_id, job["job_id"], final_status, now,
                        {"error": error} if error else {})
            row = db.execute("SELECT * FROM sf_google_analysis_jobs WHERE tenant_id=%s AND job_id=%s",
                             (tenant_id, job["job_id"])).fetchone()
        return self._public(row, now=now)

    @staticmethod
    def _analyze(kind, rows):
        types = Counter(row["result_type"] for row in rows)
        organic = [row for row in rows if row["result_type"] == "organic"]
        positions = [row["organic_position"] for row in organic
                     if isinstance(row.get("organic_position"), int)]
        result = {
            "analysis_type": kind,
            "method_version": "deterministic-analysis-1",
            "observed_items": len(rows),
            "by_result_type": dict(sorted(types.items())),
            "organic_items": len(organic),
            "organic_position_provided": len(positions),
            "organic_position_unknown": len(organic) - len(positions),
            "unique_target_urls": len({r.get("target_url") for r in rows if r.get("target_url")}),
            "limitations": [
                "counts_only_for_frozen_manifest",
                "unknown_positions_are_not_beyond_depth",
                "not_a_global_google_population",
            ],
        }
        if kind == "rank-summary":
            result["organic_position_histogram"] = {
                str(position): positions.count(position) for position in sorted(set(positions))}
            result["top_k_observed"] = {
                str(k): sum(1 for p in positions if p <= k) for k in (1, 3, 10)}
            result["top_k_denominator"] = "organic_items_with_position_only"
        return result


class AnalysisJobWorker:
    """Separate-process polling loop over the durable analysis queue."""

    def __init__(self, service, *, worker_ref, clock=None, poll_seconds=1.0):
        self.service = service
        self.worker_ref = worker_ref
        self.clock = clock or _now
        self.poll_seconds = max(0.1, float(poll_seconds))
        self.stop = threading.Event()

    def run_once(self, *, now=None):
        current = now or self.clock()
        self.service.expire_due(now=current)
        self.service.recover_expired_leases(now=current)
        for tenant_id in self.service.tenant_ids_with_work(now=current):
            result = self.service.run_once(
                tenant_id=tenant_id, worker_ref=self.worker_ref, now=current)
            if result is not None:
                return result
        return None

    def run_forever(self):
        while not self.stop.wait(self.poll_seconds):
            result = self.run_once()
            if result is not None and result.get("status") == "running":
                self.stop.wait(self.poll_seconds)
